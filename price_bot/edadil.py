from __future__ import annotations


class EdadilProvider:
    """Едадил (Edadeal) — агрегатор акций супермаркетов.

    Честная оговорка: сайт и API Едадила требуют авторизации через Яндекс SSO,
    анонимный доступ недоступен (проверено: edadil.ru отдаёт только страницу
    входа). Поэтому живой провайдер акций здесь не работает, а акции
    показываются из Купера (поля discount/original_price в ответах API).

    Если позже появится анонимный доступ или вы захотите подключить свой
    аккаунт Едадила, реализуйте search() здесь — интерфейс уже готов.
    """

    def available(self) -> bool:
        return False

    def search(self, query: str) -> list:
        return []

    def status_message(self) -> str:
        return (
            "Едадил: нужна авторизация через Яндекс — живые акции недоступны. "
            "Акции показаны из Купера."
        )
